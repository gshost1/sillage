use serde::{Deserialize, Serialize};

/// Denominator choice for the cluster similarity constraint `s(τ) > τ3` (Section 3.3.3).
///
/// The paper's printed formula writes `s(τ) = csq(τ) / |F(N2(i1))|`. Because
/// `cs(τ) <= |F(N2(i1))|` and `l(τ) = cs(τ) / csq(τ) > 1.5`, the printed formula
/// implies `s(τ) < 1 / 1.5 ≈ 0.67`, making `s(τ) > 0.9` mathematically impossible.
/// The accompanying prose states that the intersection of pruned snippets in a cluster
/// should be "very similar to the first *pruned* snippet", so [`SDenom::PrunedFirst`]
/// (`|F(Prune(F(q), N2(i1)))|`) is the default.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum SDenom {
    PrunedFirst,
    PaperLiteral,
}

/// Feature combination operator inside `Intersect(τ, q)` (Section 3.3.3).
///
/// The paper uses multiset sum (`⊎`) for the 2-element base case and multiset union
/// (`∪`, elementwise max) for 3+ elements (`AsPaper`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum IntersectOp {
    AsPaper,
    AlwaysSum,
    AlwaysUnion,
}

/// Tuple deduplication strategy for `N3` (Section 3.3.3).
///
/// `AllEarlier` compares Jaccard similarity against every earlier tuple in the sorted
/// list (literal reading of the paper). `KeptOnly` compares only against retained tuples.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Dedup {
    AllEarlier,
    KeptOnly,
}

/// Recommendation for a size-1 cluster `(i1)` (Section 3.3.3 vs Section 4.3.5).
///
/// Section 3.3.3 defines `Intersect((i1), q) = Prune(F(q), N2(i1))`, which only keeps
/// query-matching code and so can never add anything to the query. Section 4.3.5
/// says that for clusters of size 1 "Aroma performs no intersection and recommends
/// the full method bodies without any pruning", which [`Singleton::FullBody`]
/// (the default) implements; [`Singleton::PrunedToQuery`] is the literal formula.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Singleton {
    FullBody,
    PrunedToQuery,
}

/// Which maximisers extend a tuple during cluster growth (Section 3.3.3, Decision 3).
///
/// The paper's `C_{ℓ+1}` adds `(i1..ik, i)` for *every* `i` reaching the max `l`.
/// On corpora with many structurally identical methods (generated code, test
/// suites) every candidate ties, and the literal rule enumerates every increasing
/// sequence of tied candidates, which is exponential (a 40 s Phase III was observed
/// on retrofit's `RequestFactoryTest`). [`ClusterTies::First`] (default) extends with
/// the earliest maximiser only; [`ClusterTies::All`] is the literal rule, bounded by
/// [`MAX_TUPLES`] tuples.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ClusterTies {
    First,
    All,
}

/// Safety cap on the number of tuples generated by [`ClusterTies::All`].
pub const MAX_TUPLES: usize = 5_000;

/// Algorithm hyperparameters and paper disambiguation toggles.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Params {
    /// Phase I candidate count (paper default: 1000).
    pub eta1: usize,
    /// Phase III candidate cap from reranked N2 (paper default: 100).
    pub eta2: usize,
    /// Minimum normalized pruned query similarity `SimScore(q, Prune(q, m)) / |F(q)|` (paper default: 0.65).
    pub tau1: f64,
    /// Minimum cluster extension ratio `l(τ) = cs(τ) / csq(τ)` (paper default: 1.5).
    pub tau2: f64,
    /// Minimum cluster query-alignment similarity `s(τ)` (paper default: 0.9).
    pub tau3: f64,
    /// Maximum allowed Jaccard similarity between cluster index tuples (paper default: 0.5).
    pub jaccard: f64,
    /// Maximum number of recommendations returned (paper default: 5).
    pub k: usize,
    pub s_denominator: SDenom,
    pub intersect_union: IntersectOp,
    pub dedup_against: Dedup,
    pub singleton: Singleton,
    /// Presentation post-pass on each recommendation: restore a dropped callee or
    /// member-name token whose call / member node is kept, so intersections render
    /// `setupUI(innerView)` instead of `(innerView)` (Listing 7). Not in the paper.
    pub complete_calls: bool,
    pub cluster_ties: ClusterTies,
}

impl Default for Params {
    fn default() -> Self {
        Self {
            eta1: 1000,
            eta2: 100,
            tau1: 0.65,
            tau2: 1.5,
            tau3: 0.9,
            jaccard: 0.5,
            k: 5,
            s_denominator: SDenom::PrunedFirst,
            intersect_union: IntersectOp::AsPaper,
            dedup_against: Dedup::AllEarlier,
            singleton: Singleton::FullBody,
            complete_calls: true,
            cluster_ties: ClusterTies::First,
        }
    }
}

impl Params {
    /// Thresholds for agent use on a single repository (500–50k methods).
    ///
    /// A single repo has far fewer near-duplicates than the paper's 5,417-project
    /// corpus, so the paper thresholds rarely form multi-method clusters: τ1, τ2
    /// and τ3 are softened (0.55 / 1.25 / 0.80) so that two or three peers sharing
    /// an idiom cluster, η1 / η2 are sized for a single repo, and k keeps only the
    /// few strongest recommendations an agent should read. [`Params::default`]
    /// (the paper settings used by every benchmark) is unchanged.
    pub fn repo_preset() -> Self {
        Self {
            eta1: 500,
            eta2: 60,
            tau1: 0.55,
            tau2: 1.25,
            tau3: 0.80,
            k: 3,
            ..Self::default()
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_is_the_paper_and_preset_is_softer() {
        let d = Params::default();
        assert_eq!((d.eta1, d.eta2, d.k), (1000, 100, 5));
        assert_eq!((d.tau1, d.tau2, d.tau3, d.jaccard), (0.65, 1.5, 0.9, 0.5));
        assert_eq!(d.s_denominator, SDenom::PrunedFirst);
        assert_eq!(d.intersect_union, IntersectOp::AsPaper);
        assert_eq!(d.dedup_against, Dedup::AllEarlier);
        assert_eq!(d.singleton, Singleton::FullBody);
        assert!(d.complete_calls);
        assert_eq!(d.cluster_ties, ClusterTies::First);

        let r = Params::repo_preset();
        assert_eq!((r.tau1, r.tau2, r.tau3), (0.55, 1.25, 0.80));
        assert!(r.tau1 < d.tau1 && r.tau2 < d.tau2 && r.tau3 < d.tau3);
        assert!(r.eta1 <= d.eta1 && r.eta2 <= d.eta2 && r.k <= d.k);
        assert_eq!(r.jaccard, d.jaccard);
        assert_eq!(
            Params { eta1: d.eta1, eta2: d.eta2, tau1: d.tau1, tau2: d.tau2, tau3: d.tau3, k: d.k, ..r },
            d
        );
    }
}
